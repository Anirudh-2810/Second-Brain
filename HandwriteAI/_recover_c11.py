"""Recover original c11 members (pre-harvest 70) via pipeline-calibrated match.

full_11.png was generated by _fullsheet.py when clusters.json c11 still held
all 70 members: 12 cols x 64px cells, each lib file thumbnailed to <=50px and
pasted at +6,+12. Prunes/harvest later rewrote clusters.json, orphaning 31
harvest-drops + 17 pruned-t + 4 pruned-f source files (still on disk in the
glyphs lib, just unreferenced).

Strategy: replay the exact thumbnail+paste pipeline for every lib file,
md5-match against sheet cells. Calibrate on known members (current c11 + c64)
before trusting the scan. Orphans get a contact sheet for t-eyeballing.
"""
import os, sys, json, hashlib
os.chdir(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, '.')
from PIL import Image
import profiles

_info = profiles.resolve("")
CDIR = _info["clusters"]
LIB = _info["glyphs"]
COLS, CELL = 12, 64
LAB = _info["labeled"]

payload = json.load(open(os.path.join(CDIR, 'clusters.json')))
known_c11 = set(payload['clusters']['11'])
known_c64 = set(payload['clusters']['64'])

# current c11/c64 members are already lib filenames in clusters.json
cur_c11_src = set(known_c11)
cur_c64_src = set(known_c64)
# pruned-t sources: md5-match the leftover labeled copies to the lib
lib_md5 = {}
for f in os.listdir(LIB):
    if not f.endswith('.png'):
        continue
    lib_md5[hashlib.md5(open(os.path.join(LIB, f), 'rb').read()).hexdigest()] = f
pruned_t = set()
for lf in sorted(os.listdir(LAB)):
    if not lf.startswith('c11_t_'):
        continue
    h = hashlib.md5(open(os.path.join(LAB, lf), 'rb').read()).hexdigest()
    if h in lib_md5:
        pruned_t.add(lib_md5[h])
pruned_t -= cur_c11_src
# pruned-f leftovers (c64 was pruned 19->15, labeled copies may linger)
pruned_f = set()
for lf in sorted(os.listdir(LAB)):
    if not lf.startswith('c64_f_'):
        continue
    h = hashlib.md5(open(os.path.join(LAB, lf), 'rb').read()).hexdigest()
    if h in lib_md5:
        pruned_f.add(lib_md5[h])
pruned_f -= cur_c64_src

known = cur_c11_src | cur_c64_src | pruned_t | pruned_f
print(f'known: c11={len(cur_c11_src)} c64={len(cur_c64_src)} '
      f'pruned_t={len(pruned_t)} pruned_f={len(pruned_f)} total={len(known)}')

sheet = Image.open(os.path.join(CDIR, 'full_11.png')).convert('RGB')


def sheet_cell_fp(i):
    col, row = i % COLS, i // COLS
    region = sheet.crop((col * CELL + 6, row * CELL + 12,
                         col * CELL + 6 + 50, row * CELL + 12 + 50))
    return hashlib.md5(region.tobytes()).hexdigest()


def lib_cell_fp(path):
    im = Image.open(path).convert('RGB')
    im.thumbnail((50, 50))
    canvas = Image.new('RGB', (50, 50), 'white')
    canvas.paste(im, (0, 0))
    return hashlib.md5(canvas.tobytes()).hexdigest()


sheet_fps = {}
for i in range(70):
    sheet_fps.setdefault(sheet_cell_fp(i), []).append(i)

# calibrate
ok = bad = 0
for fn in sorted(known):
    if lib_cell_fp(os.path.join(LIB, fn)) in sheet_fps:
        ok += 1
    else:
        bad += 1
        print('  CALIB MISS:', fn)
print(f'calibration: {ok}/{ok + bad} known members matched')
if ok < len(known) * 0.8:
    print('ABORT: pipeline mismatch (Pillow version drift?)')
    sys.exit(1)

# scan the lib
matched = {}
for f in os.listdir(LIB):
    if not f.endswith('.png'):
        continue
    fp = lib_cell_fp(os.path.join(LIB, f))
    if fp in sheet_fps:
        matched[f] = sheet_fps[fp]
print(f'scan matched {len(matched)} lib files to sheet cells (expect ~70)')

orphans = sorted(set(matched) - known)
print(f'orphans to review: {len(orphans)}')

# contact sheet of orphans, 12 cols, indexed
from PIL import ImageDraw
n = len(orphans)
rows = (n + COLS - 1) // COLS
out = Image.new('RGB', (COLS * CELL, rows * CELL), 'white')
d = ImageDraw.Draw(out)
for i, fn in enumerate(orphans):
    im = Image.open(os.path.join(LIB, fn)).convert('RGB')
    im.thumbnail((50, 50))
    x, y = (i % COLS) * CELL + 6, (i // COLS) * CELL + 12
    out.paste(im, (x, y))
    d.text((x, y - 11), str(i), fill='red')
out.save(os.path.join(CDIR, 'orphans_11.png'))
with open(os.path.join(CDIR, 'orphans_11.json'), 'w') as f:
    json.dump(orphans, f, indent=2)
print(f'wrote orphans_11.png + orphans_11.json ({n} files)')
